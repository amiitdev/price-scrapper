import { writeFileSync, existsSync, mkdirSync } from "fs";
import { createRequire } from "module";

const require = createRequire(import.meta.url);

try {
  const pwPath = require.resolve("playwright-core/package.json");
  const dir = pwPath.replace("/package.json", "");
  const browsersJson = dir + "/browsers.json";

  if (!existsSync(browsersJson)) {
    writeFileSync(
      browsersJson,
      JSON.stringify({
        comment: "Generated by patch-playwright.mjs for Vercel serverless",
        browsers: [],
      }),
    );
    console.log("Created stub browsers.json at", browsersJson);
  }
} catch {
  console.log("playwright-core not found, skipping patch");
}
